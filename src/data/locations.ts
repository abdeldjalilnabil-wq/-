function buildAllCountries(): CountryOption[] {
  let displayNames: Intl.DisplayNames | null = null;
  try {
    if (typeof Intl !== 'undefined' && 'DisplayNames' in Intl) {
      displayNames = new Intl.DisplayNames(['ar'], { type: 'region' });
    }
  } catch {
    displayNames = null;
  }

  const prioritySet = new Set<string>(PRIORITY_ARAB_CODES);
  const priorityList: CountryOption[] = [];
  const restList: CountryOption[] = [];

  for (const code of ALL_ISO_CODES) {
    const label = ARABIC_REGION_OVERRIDES[code] || displayNames?.of(code) || code;
    const item: CountryOption = {
      code,
      nameAr: label,
      dialCode: DIAL_CODE_BY_COUNTRY[code],
    };
    if (prioritySet.has(code)) {
      priorityList.push(item);
    } else {
      restList.push(item);
    }
  }

  restList.sort((a, b) => a.nameAr.localeCompare(b.nameAr, 'ar'));
  return [...priorityList, ...restList];
}

export const ALL_COUNTRIES: CountryOption[] = buildAllCountries();

export function getCountryByCode(code?: string): CountryOption {
  const upper = (code || 'DZ').toUpperCase();
  return (
    ALL_COUNTRIES.find((c) => c.code === upper) || {
      code: upper,
      nameAr: ARABIC_REGION_OVERRIDES[upper] || upper,
      dialCode: DIAL_CODE_BY_COUNTRY[upper],
    }
  );
}

